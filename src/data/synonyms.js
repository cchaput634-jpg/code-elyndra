// Index inverse normalisé : un token normalisé → l'ensemble complet (Set de tokens normalisés)
import { normalize } from '../utils/normalize.js'

const INDEX = new Map()
for (const group of SYNONYM_GROUPS) {
  const normGroup = group.map(normalize)
  const set = new Set(normGroup)
  for (const term of normGroup) {
    const existing = INDEX.get(term)
    if (existing) {
      for (const t of set) existing.add(t)
    } else {
      INDEX.set(term, new Set(set))
    }
  }
}

// Renvoie l'ensemble (Set) des termes normalisés équivalents à la requête,
// en incluant la requête elle-même. Match par égalité, préfixe ou substring.
export function expandQuery(rawQuery) {
  const nq = normalize(rawQuery.trim())
  const out = new Set()
  if (!nq) return out
  out.add(nq)
  for (const [term, group] of INDEX) {
    if (term === nq || term.includes(nq) || nq.includes(term)) {
      for (const t of group) out.add(t)
    }
  }
  return out
}
